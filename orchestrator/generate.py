"""Rebuild: turn an approved rule register into committed code under generated/.

Deterministic code renders everything except each rule method's body: the signatures and constants,
the Evaluator's precedence, the request and Cosmos models, the tests and the React form. The LLM writes
only the statements inside each rule's method. Pending or rejected rules are skipped and reported.
"""

from __future__ import annotations

import json
import re
import textwrap
from dataclasses import dataclass, field
from pathlib import Path

import yaml

from .extract import APP_FILE, SCHEMA_FILE, find_rules
from .llm import LLMClient

ROOT = Path(__file__).resolve().parent.parent
TEMPLATES = Path(__file__).resolve().parent / "templates"
PROMPT_FILE = Path(__file__).resolve().parent / "prompts" / "generate_rule.md"

PARTITION_KEY_FIELD = "PolicyNumber"
REQUEST_TYPES = {"Money": "decimal?", "String": "string?", "Picklist": "string?", "Boolean": "bool", "DateTime": "DateOnly"}
COMPUTED_TYPE = "decimal?"
HEADER = "// Generated by fluxora generate (Rebuild) from the approved rule register. Do not edit by hand."


class GenerateError(RuntimeError):
    pass


@dataclass
class Contract:
    """The deterministic shape of one rule's C# class; the LLM fills in the method body."""

    rule: dict
    kind: str  # "errors" | "status" | "compute"
    method: str
    returns: str
    params: list[tuple[str, str, str]]  # (C# type, parameter name, argument expression in Evaluator)
    constants: list[tuple[str, str, str]]  # (C# type, name, value literal)
    outcome: dict

    @property
    def id(self) -> str:
        return self.rule["id"]

    @property
    def signature(self) -> str:
        args = ", ".join(f"{t} {n}" for t, n, _ in self.params)
        return f"public static {self.returns} {self.method}({args})"

    def call(self) -> str:
        args = ", ".join(f"{n}: {expr}" for _, n, expr in self.params)
        return f"{self.id}.{self.method}({args})"


@dataclass
class Generation:
    files: dict[str, list[str]]  # relative path -> rule IDs it implements
    skipped: list[tuple[str, str]]  # (rule ID, status)
    contents: dict[str, bytes] = field(default_factory=dict)


# --- public entry points --------------------------------------------------------------------------


def generate(register: dict, client: LLMClient, *, root: Path = ROOT) -> Generation:
    """Render every file in memory. Nothing is written until write() is called."""
    fixture_dir = Path(register["fixture"])
    if not fixture_dir.is_absolute():
        fixture_dir = root / fixture_dir

    approved = [r for r in register["rules"] if r.get("status") == "approved"]
    skipped = [(r["id"], r.get("status", "pending")) for r in register["rules"] if r.get("status") != "approved"]
    if not approved:
        raise GenerateError("No approved rules in the register. Run `fluxora approve <run-id> --all` first.")

    columns = _schema_columns(fixture_dir / SCHEMA_FILE)
    request_types = {c["field"]: _request_type(c) for c in columns}
    found = find_rules(fixture_dir)
    contracts = _contracts(approved, register["rules"], found, request_types)

    template = PROMPT_FILE.read_text(encoding="utf-8")
    bodies, models = {}, set()
    for c in contracts:
        entry = client.complete(_render_prompt(template, c))
        models.add(entry["model"])
        bodies[c.id] = _clean_body(c.id, entry["response"])

    text: dict[str, str] = {}
    files: dict[str, list[str]] = {}
    for c in contracts:
        path = f"api/Rules/{c.id}.cs"
        text[path] = _render_rule(c, bodies[c.id])
        files[path] = [c.id]
    evaluator, evaluator_ids = _render_evaluator(contracts, register)
    text["api/Evaluator.cs"] = evaluator
    files["api/Evaluator.cs"] = evaluator_ids
    text["api/Contracts.cs"] = _render_contracts(columns)
    text["api/Data/ClaimDocument.cs"] = _render_document(columns)
    text["web/src/fields.ts"] = _render_fields(fixture_dir / APP_FILE, columns)
    for path in ("api/Contracts.cs", "api/Data/ClaimDocument.cs", "web/src/fields.ts"):
        files[path] = []

    contents = {path: body.encode("utf-8") for path, body in text.items()}
    for template_file in sorted(p for p in TEMPLATES.rglob("*") if p.is_file()):
        path = template_file.relative_to(TEMPLATES).as_posix()
        contents[path] = template_file.read_bytes()
        files[path] = [c.id for c in contracts] if path.startswith("api/tests/") and path.endswith(".cs") else []

    manifest = {
        "generatedFrom": {"runId": register.get("runId"), "fixture": register["fixture"]},
        "ruleBodyModel": ", ".join(sorted(models)),
        "skipped": [{"id": i, "status": s} for i, s in skipped],
        "files": [{"path": p, "rules": files[p]} for p in sorted(files)],
    }
    contents["manifest.json"] = (json.dumps(manifest, indent=2, ensure_ascii=False) + "\n").encode("utf-8")
    files["manifest.json"] = []
    return Generation(dict(sorted(files.items())), skipped, contents)


def write(generation: Generation, out_dir: Path) -> None:
    """Write generated files. Rules/ is cleared first so a skipped rule leaves no stale file.
    Build output, node_modules and package-lock.json are never touched."""
    rules_dir = out_dir / "api" / "Rules"
    if rules_dir.is_dir():
        for stale in rules_dir.glob("*.cs"):
            stale.unlink()
    for path, data in generation.contents.items():
        target = out_dir / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)


# --- contracts ------------------------------------------------------------------------------------


def _contracts(approved: list[dict], all_rules: list[dict], found: dict, request_types: dict) -> list[Contract]:
    computed_by_output = {r["output"]: r for r in all_rules if _kind(r) == "compute"}
    approved_ids = {r["id"] for r in approved}
    contracts = []
    for rule in approved:
        key = f"{rule['source']['file']}#{rule['source']['ref']}"
        if key not in found:
            raise GenerateError(f"{rule['id']}: the fixture no longer has {key}. Re-run `fluxora extract`.")
        outcome = found[key].outcome
        kind = _kind(rule)

        params = []
        for name in rule["inputs"]:
            if name in request_types:
                params.append((request_types[name], _camel(name), f"claim.{name}"))
            elif name in computed_by_output:
                source = computed_by_output[name]
                if source["id"] not in approved_ids:
                    raise GenerateError(
                        f"{rule['id']} needs {name} from {source['id']}, which is {source.get('status', 'pending')}. "
                        f"Approve {source['id']} or reject {rule['id']} too."
                    )
                params.append((COMPUTED_TYPE, _camel(name), _camel(name)))
            else:
                raise GenerateError(f"{rule['id']} uses input {name!r}, which is neither a Claim field nor a rule output.")
        if "Today()" in rule["formula"]:
            params.append(("DateOnly", "today", "asOf"))

        constants = []
        if kind == "errors":
            constants.append(("string", "Message", _cs_string(outcome.get("Message", rule["rule"]))))
        if kind == "status":
            if "Status" not in outcome:
                raise GenerateError(f"{rule['id']} sets Status, but the fixture gives no status value for it.")
            constants.append(("string", "Status", _cs_string(outcome["Status"])))

        method, returns = ("Compute", COMPUTED_TYPE) if kind == "compute" else ("Applies", "bool")
        contracts.append(Contract(rule, kind, method, returns, params, constants, outcome))
    return contracts


def _kind(rule: dict) -> str:
    outputs = [o.strip() for o in rule["output"].split(",")]
    if outputs == ["Errors"]:
        return "errors"
    return "status" if "Status" in outputs else "compute"


# --- rendering ------------------------------------------------------------------------------------


def _render_prompt(template: str, c: Contract) -> str:
    constants = ", ".join(f"{name} = {value}" for _, name, value in c.constants) or "(none)"
    values = {
        "id": c.id,
        "rule": c.rule["rule"],
        "file": c.rule["source"]["file"],
        "ref": c.rule["source"]["ref"],
        "formula": c.rule["formula"],
        "signature": c.signature,
        "constants": constants,
    }
    for name, value in values.items():
        template = template.replace("{{" + name + "}}", value)
    return template


def _clean_body(rule_id: str, text: str) -> str:
    fenced = re.search(r"```(?:csharp|cs|c#)?\s*\n(.*?)```", text, re.S)
    body = textwrap.dedent(fenced.group(1) if fenced else text).strip("\n").rstrip()
    if not body.strip():
        raise GenerateError(f"The LLM returned an empty method body for {rule_id}.")
    if re.search(r"^\s*(using|namespace)\b|\bclass\s+\w+|\bpublic\s+static\b", body, re.M):
        raise GenerateError(f"The LLM body for {rule_id} contains a declaration; only statements are allowed.")
    return body


def _render_rule(c: Contract, body: str) -> str:
    lines = [
        f"// Rule {c.id}",
        f"// {c.rule['rule']}",
        f"// Source: {c.rule['source']['file']}, {c.rule['source']['ref']}",
        f"// Formula: {c.rule['formula']}",
        HEADER,
        "// The method body was written by the LLM from this rule's register entry; the rest is deterministic.",
        "",
        "namespace Fluxora.Generated.Rules;",
        "",
        f"public static class {c.id}",
        "{",
    ]
    for cs_type, name, value in c.constants:
        lines.append(f"    public const {cs_type} {name} = {value};")
    if c.constants:
        lines.append("")
    lines += [f"    // Rule {c.id}", f"    {c.signature}", "    {"]
    lines += [f"        {line}".rstrip() if line.strip() else "" for line in body.splitlines()]
    lines += ["    }", "}", ""]
    return "\n".join(lines)


def _render_evaluator(contracts: list[Contract], register: dict) -> tuple[str, list[str]]:
    by_id = {c.id: c for c in contracts}
    validation = [c for c in contracts if c.kind == "errors"]
    computed = _ordered_computed([c for c in contracts if c.kind == "compute"])
    late = [c for c in contracts if c.outcome.get("LateReport") is True]

    chain, seen = [], set()
    for group in register.get("precedence", []):
        for rule_id in group:
            c = by_id.get(rule_id)
            if c and c.kind == "status" and rule_id not in seen:
                chain.append(c)
                seen.add(rule_id)
    missing = [c.id for c in contracts if c.kind == "status" and c.id not in seen]
    if missing:
        raise GenerateError(f"{', '.join(missing)} set Status but are not in the register's precedence.")

    order = " > ".join("+".join(g) for g in register.get("precedence", []))
    out = [
        HEADER,
        f"// Precedence read from the fixture by the Extractor: {order}",
        "// This file only orders the rule calls; every condition, value and message lives in Rules/.",
        "",
        "using Fluxora.Generated.Rules;",
        "",
        "namespace Fluxora.Generated;",
        "",
        "public static class Evaluator",
        "{",
        "    public static EvaluationResult Evaluate(EvaluateRequest claim, DateOnly asOf)",
        "    {",
        "        var errors = new List<string>();",
        "        var messages = new List<string>();",
    ]
    for c in validation:
        out.append(f'        if ({c.call()}) {{ errors.Add("{c.id}"); messages.Add({c.id}.Message); }}')
    out += [
        "        if (errors.Count > 0)",
        "        {",
        "            return new EvaluationResult(errors, messages, null, null, null, null, errors.ToList());",
        "        }",
        "",
        "        var fired = new SortedSet<string>(StringComparer.Ordinal);",
    ]
    outputs = {}
    for c in computed:
        var = _camel(c.rule["output"])
        outputs[c.rule["output"]] = var
        out.append(f"        var {var} = {c.call()};")
        out.append(f'        fired.Add("{c.id}");')
    if late:
        out.append(f"        bool? lateReport = {late[0].call()};")
        out.append(f'        if (lateReport == true) fired.Add("{late[0].id}");')
    else:
        out.append("        bool? lateReport = null;")
    out += ["", "        string? status = null;"]
    for i, c in enumerate(chain):
        keyword = "if" if i == 0 else "else if"
        out.append(f'        {keyword} ({c.call()}) {{ status = {c.id}.Status; fired.Add("{c.id}"); }}')
    excess, payable = outputs.get("Excess", "null"), outputs.get("Payable", "null")
    out += [
        "",
        f"        return new EvaluationResult(errors, messages, {excess}, {payable}, lateReport, status, fired.ToList());",
        "    }",
        "}",
        "",
    ]
    ids = sorted({c.id for c in validation + computed + late + chain})
    return "\n".join(out), ids


def _ordered_computed(computed: list[Contract]) -> list[Contract]:
    """Order computed rules so each runs after the rules whose outputs it reads."""
    remaining, done, ordered = list(computed), set(), []
    outputs = {c.rule["output"] for c in computed}
    while remaining:
        ready = [c for c in remaining if all(i in done or i not in outputs for i in c.rule["inputs"])]
        if not ready:
            raise GenerateError("Computed rules depend on each other in a cycle: " + ", ".join(c.id for c in remaining))
        for c in ready:
            ordered.append(c)
            done.add(c.rule["output"])
            remaining.remove(c)
    return ordered


def _render_contracts(columns: list[dict]) -> str:
    params = [f"    {_request_type(c)} {c['field']}," for c in columns]
    return "\n".join(
        [
            HEADER,
            f"// The request record mirrors the Claim table in {SCHEMA_FILE}.",
            "",
            "namespace Fluxora.Generated;",
            "",
            "/// <summary>Body of POST /claims/evaluate: the Claim fields plus an optional as-of date for Today().</summary>",
            "public sealed record EvaluateRequest(",
            *params,
            "    DateOnly? AsOf);",
            "",
            "/// <summary>What the migrated app decided for one claim. FiredRules lists the rules that decided it.</summary>",
            "public sealed record EvaluationResult(",
            "    IReadOnlyList<string> Errors,",
            "    IReadOnlyList<string> Messages,",
            "    decimal? Excess,",
            "    decimal? Payable,",
            "    bool? LateReport,",
            "    string? Status,",
            "    IReadOnlyList<string> FiredRules);",
            "",
        ]
    )


def _render_document(columns: list[dict]) -> str:
    id_field = next((c["field"] for c in columns if c.get("isPrimaryName")), columns[0]["field"])
    props, assigns = [], []
    for c in columns:
        name, kind = c["field"], c["type"]
        if name == id_field:
            props.append(f'    [JsonProperty("id")] public string Id {{ get; set; }} = "";')
            assigns.append(f'        Id = string.IsNullOrWhiteSpace(r.{name}) ? Guid.NewGuid().ToString("N") : r.{name},')
        elif name == PARTITION_KEY_FIELD:
            props.append(f'    [JsonProperty("{_camel(name)}")] public string {name} {{ get; set; }} = "";')
            assigns.append(f'        {name} = r.{name} ?? "",')
        elif name == "Status":
            props.append(f'    [JsonProperty("status")] public string? Status {{ get; set; }}')
            assigns.append("        Status = result.Status,")
        elif kind == "DateTime":
            props.append(f'    [JsonProperty("{_camel(name)}")] public string {name} {{ get; set; }} = "";')
            assigns.append(f'        {name} = r.{name}.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture),')
        else:
            props.append(f'    [JsonProperty("{_camel(name)}")] public {_request_type(c)} {name} {{ get; set; }}')
            assigns.append(f"        {name} = r.{name},")
    return "\n".join(
        [
            HEADER,
            f"// Cosmos DB document for the Claim table in {SCHEMA_FILE}. id = {id_field}; partition key = /{_camel(PARTITION_KEY_FIELD)}.",
            "",
            "using System.Globalization;",
            "using Newtonsoft.Json;",
            "",
            "namespace Fluxora.Generated.Data;",
            "",
            "public sealed class ClaimDocument",
            "{",
            *props,
            "",
            "    // The evaluation the migrated app made for this claim.",
            '    [JsonProperty("errors")] public List<string> Errors { get; set; } = new();',
            '    [JsonProperty("excess")] public decimal? Excess { get; set; }',
            '    [JsonProperty("payable")] public decimal? Payable { get; set; }',
            '    [JsonProperty("lateReport")] public bool? LateReport { get; set; }',
            '    [JsonProperty("firedRules")] public List<string> FiredRules { get; set; } = new();',
            '    [JsonProperty("evaluatedAsOf")] public string EvaluatedAsOf { get; set; } = "";',
            "",
            "    public static ClaimDocument From(EvaluateRequest r, EvaluationResult result, DateOnly asOf) => new()",
            "    {",
            *assigns,
            "        Errors = result.Errors.ToList(),",
            "        Excess = result.Excess,",
            "        Payable = result.Payable,",
            "        LateReport = result.LateReport,",
            "        FiredRules = result.FiredRules.ToList(),",
            '        EvaluatedAsOf = asOf.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture),',
            "    };",
            "}",
            "",
        ]
    )


def _render_fields(app_path: Path, columns: list[dict]) -> str:
    """Mirror ClaimScreen: one form field per control bound to a Claim field, in screen order."""
    doc = yaml.safe_load(app_path.read_text(encoding="utf-8"))
    field_names = {c["field"] for c in columns}
    title, submit, form = "Claim", "Submit", []
    for screen in (doc.get("Screens") or {}).values():
        for child in screen.get("Children") or []:
            for name, body in child.items():
                control = str(body.get("Control", ""))
                props = body.get("Properties") or {}
                text = _literal(props.get("Text"))
                if "Label" in control and text and title == "Claim":
                    title = text
                if "Button" in control and text:
                    submit = text
                m = re.match(r"(txt|drp|dp|chk)([A-Z]\w*)$", name)
                if not m or m.group(2) not in field_names:
                    continue
                field_name = m.group(2)
                entry = {"name": _camel(field_name), "control": name, "kind": "text", "label": _humanise(field_name)}
                if "TextInput" in control:
                    entry["kind"] = "number" if "TextFormat.Number" in str(props.get("Format", "")) else "text"
                    hint = _literal(props.get("HintText"))
                    if hint:
                        label, _, placeholder = hint.partition(", ")
                        entry["label"] = label
                        if placeholder:
                            entry["placeholder"] = placeholder
                elif "DropDown" in control:
                    entry["kind"] = "select"
                    entry["options"] = json.loads(str(props.get("Items", "=[]")).lstrip("="))
                elif "DatePicker" in control:
                    entry["kind"] = "date"
                elif "CheckBox" in control:
                    entry["kind"] = "checkbox"
                    entry["label"] = text or entry["label"]
                form.append(entry)
    return "\n".join(
        [
            HEADER.replace("the approved rule register", f"{APP_FILE} (ClaimScreen)"),
            'export type FieldKind = "text" | "number" | "select" | "date" | "checkbox";',
            "",
            "export interface Field {",
            "  name: string;",
            "  control: string;",
            "  kind: FieldKind;",
            "  label: string;",
            "  placeholder?: string;",
            "  options?: string[];",
            "}",
            "",
            f"export const screenTitle = {json.dumps(title, ensure_ascii=False)};",
            f"export const submitLabel = {json.dumps(submit, ensure_ascii=False)};",
            "",
            f"export const fields: Field[] = {json.dumps(form, indent=2, ensure_ascii=False)};",
            "",
        ]
    )


# --- helpers --------------------------------------------------------------------------------------


def _schema_columns(path: Path) -> list[dict]:
    schema = json.loads(path.read_text(encoding="utf-8"))
    return [c for t in schema.get("tables", []) for c in t.get("columns", []) if "field" in c]


def _request_type(column: dict) -> str:
    if column["type"] not in REQUEST_TYPES:
        raise GenerateError(f"Column {column['field']} has type {column['type']}, which has no C# mapping yet.")
    return REQUEST_TYPES[column["type"]]


def _camel(name: str) -> str:
    return name[:1].lower() + name[1:]


def _humanise(name: str) -> str:
    words = re.findall(r"[A-Z][a-z]*", name)
    return " ".join([words[0]] + [w.lower() for w in words[1:]]) if words else name


def _literal(value: object) -> str | None:
    m = re.fullmatch(r'=\s*"([^"]*)"', str(value or "").strip())
    return m.group(1) if m else None


def _cs_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'
